// One profile per contract the coordinator can run. The twinvee profile pins
// the existing escrow path's exact inputs; any other profile takes the generic
// payment-terms path. Folders, file names, EDGAR links and the assumptions
// fixture name all come from here so the pipeline never hardcodes a contract.
export type ContractProfile = {
  id: string;
  boxFolder: string;
  // Required contract PDFs, in document order.
  fileNames: string[];
  // Optional files fetched and versioned like the PDFs when present.
  cashFileName: string;
  replyFileName?: string;
  // Public EDGAR link shown on the page and in the draft, keyed by file name.
  edgarUrls: Record<string, string>;
  // Assumptions fixture under the fixtures dir used when no cash file exists.
  assumptionsFixture: string;
  // Private reviewer-confirmation file under the reviews dir (generic path).
  reviewFileName?: string;
  // The file whose sections drive the escrow path's typed calls (twinvee only —
  // the generic path extracts over every section of every file).
  operativeFile?: string;
  path: "escrow" | "payment_terms";
};

